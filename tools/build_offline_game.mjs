import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const web = 'web';
const entry = 'src/game/main.js';
const modules = {};
const specifier = file => `@tod/${file}`;

async function collect(file) {
  if (Object.hasOwn(modules, specifier(file))) return;
  const code = await readFile(path.join(root, web, file), 'utf8');
  const dependencies = new Set();
  modules[specifier(file)] = code.replace(/^(import\s+[\s\S]*?\sfrom\s*)(['"])(\.\.?\/[^'"]+)\2/gm,
    (_, prefix, quote, relative) => {
      const dependency = path.posix.join(path.posix.dirname(file), relative);
      dependencies.add(dependency);
      return `${prefix}${quote}${specifier(dependency)}${quote}`;
    });
  for (const dependency of dependencies) await collect(dependency);
}

await collect(entry);
const rig = JSON.parse(await readFile(path.join(root, 'assets/rig/hero-quarter.rig.json'), 'utf8'));
const bootstrap = `// Generated by tools/build_offline_game.mjs. Edit the original modules.
(() => {
  const sources = ${JSON.stringify(modules)};
  const imports = Object.fromEntries(Object.entries(sources).map(([name, code]) => [
    name, URL.createObjectURL(new Blob([code], { type: 'text/javascript' })),
  ]));
  const map = document.createElement('script');
  map.type = 'importmap';
  map.textContent = JSON.stringify({ imports });
  document.head.append(map);
  globalThis.todOfflineRig = ${JSON.stringify(rig)};
  globalThis.todOfflineStart = import(${JSON.stringify(specifier(entry))}).finally(() => {
    Object.values(imports).forEach(url => URL.revokeObjectURL(url));
  });
})();
`;
await writeFile(path.join(root, web, 'src/game/offline.js'), bootstrap);
